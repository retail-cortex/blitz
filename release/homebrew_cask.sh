# Prints the Homebrew cask for a release's desktop app (spec_025_release
# REL-16a), from the SHA-256 checksums of its two macOS disk images
# (sha256sum's format):
#
#   release/homebrew_cask.sh 0.1.0 dmg-checksums.txt > Casks/blitz.rb
#
# The homebrew workflow pushes it to the retail-cortex/homebrew-tap
# repository when a release is published, so `brew install --cask
# retail-cortex/tap/blitz` installs it.

set -euo pipefail

version="${1:?usage: homebrew_cask.sh <version> <dmg-checksums.txt>}"
sums="${2:?usage: homebrew_cask.sh <version> <dmg-checksums.txt>}"
version="${version#v}"

sha() {
  local f="Blitz_${version}_macos_$1.dmg" s
  s="$(awk -v f="$f" '{ n = $2; sub(/^\*/, "", n); sub(/.*\//, "", n) } n == f { print $1 }' "$sums")"
  [ -n "$s" ] || { echo "homebrew_cask: $f isn't in $sums" >&2; exit 1; }
  echo "$s"
}

# Each assignment fails the script when a disk image is missing.
arm64="$(sha arm64)"
x64="$(sha x64)"

cat <<RUBY
# Generated by release/homebrew_cask.sh for Blitz $version.
cask "blitz" do
  arch arm: "arm64", intel: "x64"

  version "$version"
  sha256 arm:   "${arm64}",
         intel: "${x64}"

  url "https://github.com/retail-cortex/blitz/releases/download/v#{version}/Blitz_#{version}_macos_#{arch}.dmg"
  name "Blitz"
  desc "AI agent for your workspace: code, documents, research and data"
  homepage "https://retail-cortex.github.io/blitz/"

  # The app updates itself when it quits.
  auto_updates true
  depends_on macos: :ventura

  app "Blitz.app"

  # The service and the tray run from inside Blitz.app.
  uninstall launchctl: ["dev.blitz.service", "dev.blitz.tray"],
            quit:      "dev.blitz.desktop"

  # ~/.blitz (settings, sessions, keys) is shared with the blitz formula
  # and stays.
  zap trash: [
    "~/Library/Application Support/Blitz",
    "~/Library/Caches/dev.blitz.desktop",
    "~/Library/HTTPStorages/dev.blitz.desktop",
    "~/Library/Preferences/dev.blitz.desktop.plist",
    "~/Library/Saved Application State/dev.blitz.desktop.savedState",
  ]
end
RUBY
